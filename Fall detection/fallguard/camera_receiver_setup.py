def setup():
    if CONFIG.exists() or CONNECTION.exists():
        print('[STOP] Cau hinh camera da ton tai. KHONG ghi de mat khau dang dung.')
        print('       Sao luu / xoa mediamtx.yml va LARIX_CONNECTION.txt neu muon tao credential moi.')
        return 1
    pubpass=secrets.token_hex(20)
    readpass=secrets.token_hex(20)
    rtsp=f'rtsp://fallguard_read:{readpass}@127.0.0.1:8554/live/fallguard'
    backup = ROOT / '.env.backup.camera'
    if not backup.exists():
        shutil.copy2(ENV, backup)
    update_env({'CCTV_URL':rtsp, 'CCTV_NAME':'Camera Larix', 'CCTV_AUTOSTART':'1'})
    CONFIG.write_text(make_config(pubpass,readpass), encoding='utf-8')
    CONNECTION.write_text('FALLGUARD - CONNECTION DETAILS (PRIVATE)\n'
                          '=======================================\n'
                          'Server: Larix Broadcaster -> RTMPS -> Tailscale Funnel :8443 -> MediaMTX.\n'
                          'Trong Streamlabs: Other (Custom RTMP):\n'
                          'Server URL: rtmps://YOUR-NODE.YOUR-TAILNET.ts.net:8443/live\n'
                          'Stream Key: fallguard?user=fallguard_publish&pass='+pubpass+'\n'
                          'Trong Larix (neu dung):\n'
                          'URL: rtmps://YOUR-NODE.YOUR-TAILNET.ts.net:8443/live/fallguard\n'
                          'Login: fallguard_publish ; Password: '+pubpass+'\n'
                          'Local RTSP (CHI TREN PC): '+rtsp+'\n'
                          'THAY YOUR-NODE.YOUR-TAILNET.ts.net bang ten mien Tailscale Funnel cua ban.\n'
                          'KHONG public file nay, .env, hoac mediamtx.yml.\n',encoding='utf-8')
    print('[OK] Created mediamtx.yml and CCTV_URL in .env')
    print('[OK] Connection instructions saved: LARIX_CONNECTION.txt')
    print('[NOTE] Keep all generated credentials private. Restart FallGuard server.')
    return 0


def download():
    if BINARY.exists():
        print('[OK] MediaMTX executable exists.');return 0
    if sys.platform!='win32':
        print('[NOTE] Download only works on Windows. See MediaMTX official release for your OS.')
        return 1
    print('[DOWNLOAD] MediaMTX '+VERSION+' (official GitHub release)')
    BINARY.parent.mkdir(parents=True,exist_ok=True)
    tmp = None
    try:
        with tempfile.NamedTemporaryFile(delete=False,suffix='.zip') as file:
            tmp=Path(file.name)
        req=urllib.request.Request(ZIP_URL,headers={'User-Agent':'FallGuard-MediaMTX-setup'})
        with urllib.request.urlopen(req,timeout=50) as response, tmp.open('wb') as out:
            shutil.copyfileobj(response,out)
        with tmp.open('rb') as content:
            checksum=hashlib.file_digest(content,'sha256').hexdigest()
        if checksum != SHA256:
            raise RuntimeError('MediaMTX SHA256 checksum mismatch; download refused.')
        with zipfile.ZipFile(tmp) as z:
            binary=next((f for f in z.infolist() if Path(f.filename).name.lower()=='mediamtx.exe'),None)
            if binary is None or binary.file_size > 200_000_000:
                raise RuntimeError('Archive does not contain expected executable.')
            with z.open(binary) as src, BINARY.open('wb') as dst: shutil.copyfileobj(src,dst)
        print('[OK] MediaMTX installed at tools\\mediamtx.exe')
        return 0
    except Exception as exc:
        BINARY.unlink(missing_ok=True)
        print('[ERROR] Could not download MediaMTX:',str(exc))
        print('Manual download:',ZIP_URL)
        return 1
    finally:
        if tmp is not None: tmp.unlink(missing_ok=True)



def _read_local_reader_password(config_path=None):
    """Read only the local RTSP reader from the MediaMTX config we generate.

    Does not change the MediaMTX publishing account or send passwords anywhere.
    Fail closed if the structure is unfamiliar rather than guessing credentials.
    """
    config_path = config_path or CONFIG
    if not config_path.is_file():
        raise ValueError('Thieu mediamtx.yml; khong the dong bo tai khoan RTSP.')
    in_auth = False
    reader = False
    password = None
    for raw in config_path.read_text(encoding='utf-8-sig').splitlines():
        if raw.strip() == 'authInternalUsers:':
            in_auth = True
            continue
        if in_auth and raw and not raw[0].isspace() and not raw.startswith('#'):
            in_auth = False
            reader = False
        if not in_auth:
            continue
        found_user = re.fullmatch(r'\s*- user:\s*([a-zA-Z0-9_-]+)\s*', raw)
        if found_user:
            reader = found_user.group(1) == 'fallguard_read'
            continue
        if reader:
            found_pass = re.fullmatch(r'\s*pass:\s*(.+?)\s*', raw)
            if found_pass:
                raw_password = found_pass.group(1).strip()
                if len(raw_password) >= 2 and raw_password[0] == raw_password[-1] and raw_password[0] in ("'", '"'):
                    raw_password = raw_password[1:-1]
                if not raw_password or raw_password.lower() in ('null', '~'):
                    raise ValueError('Mat khau fallguard_read trong mediamtx.yml khong hop le.')
                if password is not None:
                    raise ValueError('Co nhieu tai khoan fallguard_read trong mediamtx.yml.')
                password = raw_password
                reader = False
    if password is None:
        raise ValueError('Khong tim thay tai khoan fallguard_read trong mediamtx.yml.')
    return password


def _existing_camera_url():
    """Read CCTV_URL only; never dump the .env file into logs."""
    if not ENV.is_file():
        raise ValueError('Thieu .env. Hay chay START_WINDOWS.bat de tao .env truoc.')
    from .telegram_config import _read_env
    return _read_env(ENV).get('CCTV_URL', '').strip()


def camera_auth_status():
    """Return (is_matching, expected_url), without printing sensitive values."""
    password = _read_local_reader_password()
    expected = f'rtsp://fallguard_read:{quote(password, safe="")}@127.0.0.1:8554/live/fallguard'
    current = _existing_camera_url()
    if current:
        try:
            parts = urlsplit(current)
            if (parts.scheme.lower() != 'rtsp'
                    or parts.hostname != '127.0.0.1'
                    or parts.port != 8554
                    or parts.path != '/live/fallguard'):
                raise ValueError('CCTV_URL la camera khac. Khong ghi de cau hinh khong thuoc MediaMTX local.')
        except ValueError as exc:
            raise ValueError('CCTV_URL khong phai stream MediaMTX local, khong tu ghi de.') from exc
    return current == expected, expected


def diagnose():
    """Read-only check. Safe to run before starting FallGuard."""
    if not CONFIG.exists() or not ENV.exists():
        print('[CAMERA] Khong co cau hinh MediaMTX local va/hoac .env; bo qua kiem tra.'); return 0
    try:
        matches, expected = camera_auth_status()
    except ValueError as exc:
        print('[CAMERA] Khong the doi chieu RTSP:', str(exc)); return 1
    override = os.environ.get('CCTV_URL')
    if override and override != expected:
        print('[CAMERA] CANH BAO: CCTV_URL trong bien moi truong Windows khac .env va se duoc uu tien.')
        print('[CAMERA] Hay xoa/sua bien moi truong Windows CCTV_URL, sau do khoi dong lai.')
    if matches:
        print('[CAMERA] CCTV_URL da khop tai khoan doc stream trong mediamtx.yml.')
    else:
        print('[CAMERA] CCTV_URL chua khop mat khau doc RTSP trong mediamtx.yml.')
        print('[CAMERA] Dong server, chay REPAIR_CAMERA_AUTH.bat, sau do khoi dong lai.')
    return 0


def repair():
    """Explicitly sync the RTSP READ URL in .env. Never rotate publish credentials."""
    matches, expected = camera_auth_status()
    if matches:
        print('[OK] Mat khau doc camera RTSP da khop, khong can thay doi.'); return 0
    backup = ROOT / '.env.backup.camera-auth'
    if not backup.exists():
        shutil.copy2(ENV, backup)
    update_env({'CCTV_URL': expected})
    print('[OK] Da dong bo CCTV_URL trong .env theo mediamtx.yml.')
    print('[OK] KHONG doi mat khau Larix/Streamlabs, MediaMTX hoac Telegram Gateway.')
    override = os.environ.get('CCTV_URL')
    if override and override != expected:
        print('[WARN] Windows dang co CCTV_URL rieng ghi de .env. Hay xoa/sua bien do roi restart.')
    print('[NOTE] Da sao luu .env lan dau vao .env.backup.camera-auth (giu rieng tu).')
    print('[NEXT] Dong va khoi dong lai START_WINDOWS.bat. Giu MediaMTX dang chay.')
    return 0

def check():
    if not CONFIG.exists() or not ENV.exists():
        print('[ERROR] Run SETUP_CAMERA_RECEIVER.bat first.'); return 1
    for port in (1935,8554):
        try:
            with socket.create_connection(('127.0.0.1',port),timeout=2):
                print(f'[OK] 127.0.0.1:{port} listening')
        except OSError:
            print(f'[WAIT] 127.0.0.1:{port} not listening - run RUN_MEDIAMTX.bat')
    print('[NOTE] This does not prove a remote Larix camera is publishing.')
    return 0

if __name__=='__main__':
    name=sys.argv[1] if len(sys.argv)>1 else ''
    if name not in ('setup','download','check','diagnose','repair'):
        print('Use: setup | download | check | diagnose | repair'); sys.exit(2)
    try: sys.exit(globals()[name]())
    except ValueError as exc:
        print('[ERROR]',exc); sys.exit(1)
