"""Generate private MediaMTX credentials/config for one Larix -> FallGuard stream.

No shell execution, no passwords embedded in the distributable package.
Run: python camera_receiver_setup.py setup|download|check
"""
from pathlib import Path
from urllib.parse import quote, urlsplit
import os
import re
import secrets
import hashlib
import shutil
import socket
import sys
import tempfile
import urllib.request
import zipfile

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / 'mediamtx.yml'
ENV = ROOT / '.env'
CONNECTION = ROOT / 'LARIX_CONNECTION.txt'
VERSION = 'v1.21.2'
ZIP_URL = f'https://github.com/bluenviron/mediamtx/releases/download/{VERSION}/mediamtx_{VERSION}_windows_amd64.zip'
BINARY = ROOT / 'tools' / 'mediamtx.exe'
SHA256 = 'a84224f5a490855684e62ba6fb71e80ea2a5e16aed61883bb58380290e93e467'


def update_env(replacements):
    if not ENV.exists():
        raise ValueError('Thieu .env: hay khoi dong START_WINDOWS.bat de tao .env truoc.')
    original = ENV.read_text(encoding='utf-8-sig').splitlines()
    lines, found = [], set()
    for line in original:
        key, eq, _ = line.partition('=')
        if eq and key.strip() in replacements:
            k=key.strip()
            lines.append(k+'='+replacements[k])
            found.add(k)
        else:
            lines.append(line)
    for key in replacements:
        if key not in found:
            lines.append(key+'='+replacements[key])
    ENV.write_text('\n'.join(lines)+'\n',encoding='utf-8')


